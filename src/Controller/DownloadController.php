<?php

namespace Drupal\blaetter_export_epub\Controller;

use Drupal\blaetter_export_epub\EpubCredentials;
use Drupal\Core\Access\AccessResult;
use Drupal\Core\Controller\ControllerBase;
use Drupal\Core\Session\AccountInterface;
use Drupal\Core\Url;
use Drupal\node\NodeInterface;
use Drupal\nodeshop\NodeShop;
use Drupal\user\UserInterface;
use GuzzleHttp\ClientInterface;
use Psr\Http\Message\StreamInterface;
use Symfony\Component\DependencyInjection\ContainerInterface;
use Symfony\Component\HttpFoundation\RedirectResponse;
use Symfony\Component\HttpFoundation\StreamedResponse;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;

/**
 * Delivers the watermarked ePubs generated by pepgen.
 *
 * @package Drupal\blaetter_export_epub\Controller
 */
class DownloadController extends ControllerBase
{
    /**
     * Nodes with a lower id are too old to be offered as ePub.
     */
    const MIN_NODE_ID = 25756;

    /**
     * Every ePub is a zip archive, so it starts with the signature of a zip file.
     */
    const EPUB_SIGNATURE = "PK\x03\x04";

    /**
     * The size of the chunks the ePub is passed through to the client.
     */
    const CHUNK_SIZE = 8192;

    /**
     * The http client.
     *
     * @var ClientInterface
     */
    protected $httpClient;

    public function __construct(ClientInterface $http_client)
    {
        $this->httpClient = $http_client;
    }

    /**
     * {@inheritdoc}
     */
    public static function create(ContainerInterface $container)
    {
        return new static(
            $container->get('http_client')
        );
    }

    /**
    * Checks access for the epub downloads
    *
    * @param \Drupal\Core\Session\AccountInterface $account
    *   Run access checks for this account.
    * @param int|string|null $node
    *   The (raw) id of the node.
    */
    public function access(AccountInterface $account, $node = null)
    {
        // if there is no node or the node is too old, return 404
        if (null == $node || self::MIN_NODE_ID > $node) {
            throw new NotFoundHttpException();
        }

        $node = $this->entityTypeManager()->getStorage('node')->load($node);

        // if there was no load after loading the node id, return 404, too.
        if (!$node instanceof NodeInterface) {
            throw new NotFoundHttpException();
        }

        $user = $this->entityTypeManager()->getStorage('user')->load($account->id());
        if (!$user instanceof UserInterface) {
            return AccessResult::forbidden()->setCacheMaxAge(0);
        }

        // if there is a node, check, if the user has access to it via NodeShop::grantUserAccess()
        // The access depends on the purchases of the user, so it must not be cached.
        return AccessResult::allowedIf(
            NodeShop::grantUserAccess(
                $node,
                $user,
                true
            )
        )->setCacheMaxAge(0);
    }

    /**
     * Controller for the download epub action
     *
     * pepgen generates the watermarked ePub first, afterwards it is fetched from pepgen and passed through to the
     * client. If anything fails, the user is lead back to the node with an error message.
     *
     * @param NodeInterface $node
     * @return StreamedResponse|RedirectResponse
     */
    public function downloadEpub(NodeInterface $node)
    {
        $user = $this->entityTypeManager()->getStorage('user')->load($this->currentUser()->id());
        $config = $this->config('blaetter_export_epub.settings');

        $credentials = new EpubCredentials(
            $node,
            $user,
            $config->get('pepgen.salt') ?? ''
        );

        // try to make the pepgen request and catch any exception that is thrown.
        // If an exception is thrown, we display a message to the end user and log the error message in
        // the drupal watchdog.
        try {
            $request = $this->httpClient->request(
                'POST',
                $config->get('pepgen.base_url') . '/',
                [
                    'headers' => [
                        'Content-type' => 'application/x-www-form-urlencoded',
                    ],
                    'form_params' => [
                        'watermark' => urlencode($credentials->getWatermark()),
                        'id' => $node->id(),
                        'token' => $credentials->getToken(),
                    ],
                ]
            );
            $response = json_decode((string) $request->getBody());
        } catch (\Exception $e) {
            $this->getLogger('blaetter_export_epub')->error(
                '[EPUB Export][Download epub]: Error during pepgen request for node @nid with message %message',
                [
                    '@nid' => $node->id(),
                    '%message' => $e->getMessage(),
                ]
            );
            $this->messenger()->addError(
                $this->t(
                    'There was an error generating your epub. Please try again.'
                )
            );
            return $this->redirectToNode($node);
        }

        if (200 != $request->getStatusCode() || 'Success' !== $response) {
            $error_message = is_scalar($response) ? (string) $response : json_encode($response);
            $this->getLogger('blaetter_export_epub')->error(
                '[EPUB Export][Download epub]: ePub Error reveived for node @nid with watermark @watermark ' .
                'and response %response',
                [
                    '@nid' => $node->id(),
                    '@watermark' => $credentials->getWatermark(),
                    '%response' => $error_message,
                ]
            );
            $this->messenger()->addError(
                $this->t(
                    'Your epub could not be downloaded, please contact us and provide the following error message: %error_message',
                    [
                        '%error_message' => $error_message
                    ]
                )
            );
            return $this->redirectToNode($node);
        }

        $download_url = $config->get('pepgen.download_url') .
            '/' .
            $credentials->getToken() .
            '.' .
            $node->id() .
            '.epub';

        // Fetch the ePub before sending any header to the client, so we can still lead him back to the node with an
        // error message, if the file is missing or broken.
        try {
            $download = $this->httpClient->request('GET', $download_url, ['stream' => true]);
            $body = $download->getBody();
            $first_chunk = $body->read(self::CHUNK_SIZE);
            if (200 != $download->getStatusCode() || !str_starts_with($first_chunk, self::EPUB_SIGNATURE)) {
                throw new \UnexpectedValueException(
                    'pepgen delivered no ePub (status ' . $download->getStatusCode() . ', ' .
                    strlen($first_chunk) . ' bytes)'
                );
            }
        } catch (\Exception $e) {
            $this->getLogger('blaetter_export_epub')->error(
                '[EPUB Export][Download epub]: Could not fetch the ePub for node @nid with message %message',
                [
                    '@nid' => $node->id(),
                    '%message' => $e->getMessage(),
                ]
            );
            $this->messenger()->addError(
                $this->t(
                    'There was an error generating your epub. Please try again.'
                )
            );
            return $this->redirectToNode($node);
        }

        $response = new StreamedResponse(
            function () use ($first_chunk, $body) {
                $this->passThrough($first_chunk, $body);
            },
            200,
            [
                'Content-Description' => 'File Transfer',
                'Content-Type' => 'application/epub+zip',
                'Cache-Control' => 'private, no-store',
            ]
        );
        $response->headers->set(
            'Content-Disposition',
            $response->headers->makeDisposition('attachment', 'Ebook_Blaetter.' . $node->id() . '.epub')
        );
        if ($download->hasHeader('Content-Length')) {
            $response->headers->set('Content-Length', $download->getHeaderLine('Content-Length'));
        }
        return $response;
    }

    /**
     * Passes the ePub through to the client.
     *
     * @param string $first_chunk The already read beginning of the ePub.
     * @param StreamInterface $body The rest of the ePub.
     */
    protected function passThrough(string $first_chunk, StreamInterface $body)
    {
        echo $first_chunk;
        while (!$body->eof()) {
            echo $body->read(self::CHUNK_SIZE);
            flush();
        }
        $body->close();
    }

    /**
     * Leads the user back to the node.
     *
     * @param NodeInterface $node
     * @return RedirectResponse
     */
    protected function redirectToNode(NodeInterface $node)
    {
        return new RedirectResponse(
            Url::fromRoute('entity.node.canonical', ['node' => $node->id()])->toString()
        );
    }
}
